#!/usr/bin/env python3
"""mkstack.py -- write pcb/out/gen/block_stack.v: a block AS BUILT, from the
three boards' generated modules (net2v.py's sidecars say what each port is).

    python3 mkstack.py            (sim/gen.sh runs it)

The module is called `block`, with newimpl/rtl/block.v's parameters and ports
exactly, so a newimpl bench builds with it in place of block.v (run.py), or
beside it in lockstep (lockstep.v).  It holds:

    blkhdr_bus_RevA_net     block header A, the bus board
    blkhdr_logic_RevA_net   block header B, the logic board (and its lamps)
    portcard_net   one at every PORT_FITTED slot k, every jumper at k

and wires them the way the copper does: a stack net is ONE net through all of
them (the three stacking headers join pin n of every board), a link net is one
net between A and B (J8), and every net with more than one driver is resolved
here with no z -- open drains first, then enabled drivers, then weak ones:

    value = |pd ? 0 : oe1 ? v1 : oe2 ? v2 : ... : we ? wo : 0

A net two strong drivers enable at once is a CLASH; the wrapper counts them at
every mid-cell and prints BLOCK-STACK, which fails the bench (run.py).

WHAT IS NOT A BOARD, and is simulation only (as the header comment says again):
the HCLK shim, the rc_det / cr_rel cells' clk / rst_n / tick_1k, the subscriber
card on each edge (the bench's c_tx, a_tx, ans_n, word_n), the empty-position
tie-off, the socket-commons check and the lamp check.
"""
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
PCB = HERE.parent
GEN = PCB / 'out' / 'gen'
SPEC = json.loads((PCB / 'lib' / 'block-stack.json').read_text())

CA, CB = 'blkhdr_bus_RevA', 'blkhdr_logic_RevA'
MODS = {m: json.loads((GEN / f"{m}_net.json").read_text()) for m in (CA, CB, 'portcard')}
STACK = sorted({n for c in SPEC['stack_connectors'] for n in c['pins'].values()
                if n not in ('+5V', 'GND', 'NC') and not n.startswith('SP')})
LINK = sorted({n for c in SPEC['connectors'] if c['ref'] == 'J8' for n in c['pins'].values()
               if n not in ('+5V', 'GND', 'NC')})

# the bus, as block.v's inputs (an unplugged header's pull-downs are not modelled:
# the bench always drives the bus)
BUS_IN = {'B_HCLK': 'b_hclk', 'B_SCLK': 'sclk', 'B_WR': 'wr', 'B_SDATA': 'sdata',
          'B_RESET_N': 'rst_n', 'B_RING_CAD_N': 'ring_cad_n', 'B_RBT': 'rbt', 'B_HA_N': 'ha_n',
          'B_HB_N': "1'b1", 'B_HW_N': "1'b1", 'B_WS_N': 'ws_n', 'B_UREQ_N': "1'b1", 'B_SPARE': "1'b1",
          'A_MUTE_BLK': 'mute_blk'}
for i in range(3):
    BUS_IN[f'B_SLOT{i}'] = f'slot[{i}]'
    BUS_IN[f'B_SLOTQ{i}'] = f'slotq[{i}]'
for i in range(6):
    BUS_IN[f'B_SCAN{i}'] = f'scan[{i}]'
for i in range(8):
    BUS_IN[f'B_HC{i}'] = f'hc[{i}]'
BUS_PD = {'B_HA_N': 'ha_pd', 'B_HB_N': 'hb_pd', 'B_HW_N': 'hw_pd'}
# the subscriber card on port card k's edge: the bench
EDGE_IN = {'E_C_TX': 'c_tx[k]', 'E_A_TX': 'a_tx[k]', 'E_ANS_N': 'ans_n[k]', 'E_WORD': 'word_n[k]',
           'E_RAI_N': "1'b1"}
EDGE_OUT = {'E_C_RX': 'c_rx', 'E_A_RX': 'a_rx'}


def vid(n):
    return re.sub(r'\W', '_', n)


class W:
    def __init__(self):
        self.lines = []

    def __call__(self, s=''):
        self.lines.append(s)


def contribs(mod, net):
    """What module `mod` does to `net`: (reads, [(kind, suffix)]) or None."""
    p = MODS[mod]['ports'].get(net)
    if p is None:
        return None
    kinds = []
    if p['cls'] == 'out':
        kinds.append(('out', ''))
    for sfx in p['bundle']:
        kinds.append((sfx[1:], sfx))
    return (p['cls'] in ('in', 'bundle'), kinds)


def main():
    w = W()
    w('// GENERATED by pcb/sim/mkstack.py from the three boards\' netlists -- do not edit.')
    w('//')
    w(f'// A block AS BUILT: block header A ({CA}), block header B ({CB}), and a')
    w('// port card at every fitted slot, wired as the stacking headers and the header')
    w('// link J8 wire them.  Called `block`, with newimpl/rtl/block.v\'s parameters and')
    w('// ports exactly.  See mkstack.py for what is simulation only.')
    w('`timescale 1ns/1ps')
    w('`include "exch.vh"')
    w('')
    w('module block #(')
    w("    parameter [2:0]  BLOCK       = 3'd0,")
    w("    parameter        JUMPERED    = 1'b1,")
    w("    parameter [7:0]  PORT_FITTED = 8'hFF,")
    w("    parameter [8:0]  T_ARM       = 9'd16,")
    w("    parameter [8:0]  T_REL       = 9'd256")
    w(')(')
    ports = ['input clk', 'input rst_n', 'input [2:0] slot', 'input [2:0] slotq', 'input cap_stb',
             'input frame_stb', 'input tick_1k', 'input [`SCANW-1:0] scan', 'input fill', 'input rbt',
             'input ring_cad_n', 'input [7:0] hc', 'output hc_out', 'input ha_n', 'output ha_pd',
             'output hb_pd', 'input [7:0] c_tx', 'input [7:0] a_tx', 'input [7:0] ans_n',
             'input [7:0] word_n', 'output [7:0] c_rx', 'output [7:0] a_rx', 'input mute_blk',
             'input sdata', 'input sclk', 'input wr', 'input ws_n', 'output hw_pd', 'output [7:0] port_busy']
    for i, p in enumerate(ports):
        w(f"    {p}{',' if i < len(ports) - 1 else ''}")
    w(');')
    w('    // ---- an empty position: no jumper and no port card is no board at all ----')
    w('    generate if (!JUMPERED && PORT_FITTED == 8\'d0) begin : absent')
    w("        assign hc_out = 1'b0; assign ha_pd = 1'b0; assign hb_pd = 1'b0; assign hw_pd = 1'b0;")
    w("        assign c_rx = 8'd0; assign a_rx = 8'd0; assign port_busy = 8'd0;")
    w("        wire _unused = &{1'b0, clk, rst_n, slot, slotq, cap_stb, frame_stb, tick_1k, scan, fill, rbt,")
    w("                         ring_cad_n, hc, ha_n, c_tx, a_tx, ans_n, word_n, mute_blk, sdata, sclk, wr, ws_n, 1'b0};")
    w('    end else begin : present')
    w('')
    w('    // ---- the HCLK shim: low for ticks 4-7, as clock_card.v makes it -------')
    w('    reg [1:0] hn;')
    w('    always @(posedge clk or negedge rst_n)')
    w("        if (!rst_n)       hn <= 2'd0;")
    w("        else if (cap_stb) hn <= 2'd3;")
    w("        else if (hn != 0) hn <= hn - 2'd1;")
    w("    wire b_hclk = !(cap_stb || hn != 2'd0);")
    w('')

    # ---- the shared nets: stack (A, B, cards) and link (A, B)
    shared = [(n, 'stack') for n in STACK] + [(n, 'link') for n in LINK if n not in STACK]
    w('    // ---- the shared nets: one wire each, resolved below --------------------')
    for n, _ in shared:
        w(f"    wire s_{vid(n)};")
    w('')
    # per-module driver wires
    drivers = {n: [] for n, _ in shared}      # net -> [(kind, expr_oe, expr_v)]
    for mod, tag in ((CA, 'a'), (CB, 'b')):
        for n, _ in shared:
            c = contribs(mod, n)
            if c is None:
                continue
            for kind, sfx in c[1]:
                w(f"    wire {tag}_{vid(n)}{sfx or '_out'};")
            ks = dict(c[1])
            if 'out' in ks:
                drivers[n].append(('strong', "1'b1", f"{tag}_{vid(n)}_out"))
            if 'oe' in ks:
                drivers[n].append(('strong', f"{tag}_{vid(n)}_oe", f"{tag}_{vid(n)}_o"))
            if 'pd' in ks:
                drivers[n].append(('pd', f"{tag}_{vid(n)}_pd", None))
            if 'we' in ks:
                drivers[n].append(('weak', f"{tag}_{vid(n)}_we", f"{tag}_{vid(n)}_wo"))
    # port cards: arrays, one bit a slot
    card_kinds = {}
    for n, where in shared:
        if where != 'stack':
            continue
        c = contribs('portcard', n)
        if c is None:
            continue
        card_kinds[n] = [k for k, _ in c[1]]
        for k in card_kinds[n]:
            w(f"    wire [7:0] pc_{vid(n)}_{k};")
        ks = card_kinds[n]
        if 'out' in ks:
            for i in range(8):
                drivers[n].append(('strong', f"PORT_FITTED[{i}]", f"pc_{vid(n)}_out[{i}]"))
        if 'oe' in ks:
            for i in range(8):
                drivers[n].append(('strong', f"pc_{vid(n)}_oe[{i}]", f"pc_{vid(n)}_o[{i}]"))
        if 'pd' in ks:
            drivers[n].append(('pd', f"(|pc_{vid(n)}_pd)", None))
        if 'we' in ks:
            for i in range(8):
                drivers[n].append(('weak', f"pc_{vid(n)}_we[{i}]", f"pc_{vid(n)}_wo[{i}]"))
    # the WORD lanes: the subscriber card's open drain, through port card k's JP4
    # (a jumper between two nets that both leave the card: net2v cannot carry it)
    for k in range(8):
        n = f"WORD{k}"
        if n in drivers:
            drivers[n].append(('pd', f"(PORT_FITTED[{k}] && !word_n[{k}])", None))
    w('')
    w('    // ---- resolution: open drains, then enabled drivers, then weak ones ------')
    clash_terms = []
    for n, _ in shared:
        ds = drivers[n]
        pds = [d[1] for d in ds if d[0] == 'pd']
        strong = [d for d in ds if d[0] == 'strong']
        weak = [d for d in ds if d[0] == 'weak']
        expr = "1'b0"
        for d in reversed(weak):
            expr = f"{d[1]} ? {d[2]} : {expr}"
        for d in reversed(strong):
            expr = d[2] if d[1] == "1'b1" else f"{d[1]} ? {d[2]} : {expr}"
        if pds:
            expr = f"({' || '.join(pds)}) ? 1'b0 : ({expr})"
        if not ds:
            expr = "1'b0"
        w(f"    assign s_{vid(n)} = {expr};")
        if len(strong) > 1:
            oes = ' + '.join(f"{{7'd0, {d[1]}}}" for d in strong)
            clash_terms.append((n, f"(({oes}) > 8'd1)"))
    w('')

    # ---- the three boards
    def conn(mod, inst, tag, ind, per_card=False):
        out = []
        m = MODS[mod]
        for s in m['sim_inputs']:
            out.append(f".{s}({s})")
        for pn, p in m['ports'].items():
            if p['cls'] == 'probe':
                out.append(f".{pn}({tag}_{pn})")
                continue
            c = contribs(mod, pn)
            reads, kinds = c
            shared_net = pn in drivers
            if shared_net:
                if reads:
                    out.append(f".{pn}(s_{vid(pn)})")
                for k, sfx in kinds:
                    if per_card:
                        out.append(f".{pn}{sfx or ''}(pc_{vid(pn)}_{k}[k])" if sfx else f".{pn}(pc_{vid(pn)}_out[k])")
                    else:
                        out.append(f".{pn}{sfx or ''}({tag}_{vid(pn)}{sfx or '_out'})" if sfx else
                                   f".{pn}({tag}_{vid(pn)}_out)")
                continue
            # not shared: a bus / adapter / edge / test net of this board alone
            src = None
            if not per_card and pn in BUS_IN:
                src = BUS_IN[pn]
            if per_card and pn in EDGE_IN:
                src = EDGE_IN[pn]
            own = {k: f"{tag}_{vid(pn)}_{k}" for k, _ in kinds}
            for k, sfx in kinds:
                if k == 'out':
                    out.append(f".{pn}({tag}_{vid(pn)}_out)")
                else:
                    out.append(f".{pn}{sfx}({own[k]})")
            if reads:
                if src is None:
                    # the board's own value: its enabled driver, else its weak one, else 0
                    e = "1'b0"
                    if 'we' in own:
                        e = f"{own['we']} ? {own['wo']} : {e}"
                    if 'oe' in own:
                        e = f"{own['oe']} ? {own['o']} : {e}"
                    if 'pd' in own:
                        e = f"{own['pd']} ? 1'b0 : ({e})"
                    src = e
                out.append(f".{pn}({src})")
        return out

    def local_wires(mod, tag, ind):
        L = []
        for pn, p in MODS[mod]['ports'].items():
            if p['cls'] == 'probe':
                L.append(f"{ind}wire {'[%d:0] ' % (p['width'] - 1) if p['width'] else ''}{tag}_{pn};")
                continue
            if pn in drivers:
                continue
            for k, sfx in contribs(mod, pn)[1]:
                L.append(f"{ind}wire {tag}_{vid(pn)}_{k};")
        return L

    w('    // ---- block header A, the bus board --------------------------------------')
    for l in local_wires(CA, 'a', '    '):
        w(l)
    w(f'    {CA}_net #(.JUMPERED(JUMPERED), .BLOCK(BLOCK)) u_hdra (')
    cs = conn(CA, 'u_hdra', 'a', '        ')
    for i, c in enumerate(cs):
        w(f"        {c}{',' if i < len(cs) - 1 else ''}")
    w('    );')
    w("    assign ha_pd = a_B_HA_N_pd;")
    w("    assign hb_pd = a_B_HB_N_pd;")
    w("    assign hw_pd = a_B_HW_N_pd;")
    w("    assign hc_out = a_HC_OUT_oe ? a_HC_OUT_o : 1'b0;   // /FIT open: the '244 lets go")
    w('')
    w('    // ---- block header B, the logic board ------------------------------------')
    for l in local_wires(CB, 'b', '    '):
        w(l)
    w(f'    {CB}_net u_hdrb (')
    cs = conn(CB, 'u_hdrb', 'b', '        ')
    for i, c in enumerate(cs):
        w(f"        {c}{',' if i < len(cs) - 1 else ''}")
    w('    );')
    w('')
    w('    // ---- a port card at every fitted slot, POS = LANE = k ----------------')
    w('    genvar k;')
    w('    for (k = 0; k < 8; k = k + 1) begin : pc')
    w('        if (PORT_FITTED[k]) begin : fitted')
    for l in local_wires('portcard', 'c', '            '):
        w(l)
    w('            portcard_net #(.T_ARM(T_ARM), .T_REL(T_REL), .POS(k[2:0]), .LANE(k)) u_card (')
    cs = conn('portcard', 'u_card', 'c', '                ', per_card=True)
    for i, c in enumerate(cs):
        w(f"                {c}{',' if i < len(cs) - 1 else ''}")
    w('            );')
    for pn, dst in EDGE_OUT.items():
        w(f"            assign {dst}[k] = c_{pn}_oe ? c_{pn}_o : 1'b0;")
    w("            assign port_busy[k] = !c_BUSY_N_out;")
    w('        end else begin : empty')
    for n, ks in card_kinds.items():
        for kk in ks:
            w(f"            assign pc_{vid(n)}_{kk}[k] = 1'b0;")
    for dst in EDGE_OUT.values():
        w(f"            assign {dst}[k] = 1'b0;")
    w("            assign port_busy[k] = 1'b0;")
    w('        end')
    w('    end')
    w('')
    # ---- checks
    w('    // ---- the stack\'s own checks, at every mid-cell once two frames are past --')
    w('    // Contention on a shared net, and the socket commons against frame_decode.v')
    w('    // (no bench reads a block\'s own TX_CLK, LOOP_HB, TX_OCT, RX_OCT or FILL).')
    w('    // Any line starting BLOCK-STACK fails the bench in run.py.')
    w('    integer n_chk = 0, n_bad = 0, n_clash = 0, n_frames = 0;')
    w('    always @(posedge clk or negedge rst_n)')
    w('        if (!rst_n) n_frames <= 0;')
    w('        else if (frame_stb && n_frames < 3) n_frames <= n_frames + 1;')
    w('    always @(posedge clk)')
    w('        if (rst_n && cap_stb && n_frames >= 3) begin')
    w('            if (JUMPERED) begin')
    w('                n_chk = n_chk + 1;')
    w("                if (s_TX_CLK !== ~slot[2] || s_LOOP_HB !== ~slot[1] || s_TX_OCT !== (scan[2:0] == 3'd7) ||")
    w("                    s_RX_OCT !== (scan[2:0] == 3'd0) || s_FILL !== scan[0]) begin")
    w('                    n_bad = n_bad + 1;')
    w('                    if (n_bad <= 3)')
    w('                        $display("  BLOCK-STACK %m: socket commons wrong at %0t: TX_CLK %b LOOP_HB %b TX_OCT %b RX_OCT %b FILL %b, slot %0d scan %0d",')
    w('                                 $time, s_TX_CLK, s_LOOP_HB, s_TX_OCT, s_RX_OCT, s_FILL, slot, scan);')
    w('                end')
    w('            end')
    for n, t in clash_terms:
        w(f'            if {t} begin n_clash = n_clash + 1; if (n_clash <= 3) $display("  BLOCK-STACK %m: two drivers on {n} at %0t", $time); end')
    w('        end')
    w('    final if (n_bad != 0 || n_clash != 0)')
    w('        $display("  BLOCK-STACK %m: socket commons wrong at %0d of %0d samples, %0d clashes", n_bad, n_chk, n_clash);')
    w('')
    w('    // ---- the lamps: header B\'s two \'595s show, for slot k, whether card k')
    w('    // pulled /HA_L (M) and /HB_L (BUSY) at its turn\'s mid-cell 4 last pass.')
    w('    // Expected from the cards\' own drains, taken at the same instant (the')
    w('    // shift clock); compared at every mid-cell outside the block\'s turn, once')
    w('    // a whole turn has been seen.  A lamp is lit (0) where the card pulled.')
    w('    reg [7:0] want_m, want_b, sure, seen;')
    w('    reg       whole, took, pre_m, pre_b;')
    w('    reg [2:0] tk;')
    w('    integer n_lchk = 0, n_lbad = 0;')
    w("    wire in_turn = (scan[5:3] == BLOCK);")
    w('    // /STB4 falls just after the cap_stb edge of cell 4 and the \'595 shifts on it:')
    w('    // take the card\'s drain on both sides of that instant, and trust a slot only')
    w('    // where the two agree (a hook that moves right then may read either way).')
    w('    always @(posedge clk or negedge rst_n)')
    w("        if (!rst_n) begin seen <= 8'd0; sure <= 8'd0; whole <= 1'b0; took <= 1'b0; end")
    w('        else begin')
    w("            took <= 1'b0;")
    w("            if (cap_stb && slotq == 3'd4 && in_turn) begin")
    w("                tk <= scan[2:0]; took <= 1'b1;")
    w("                pre_m <= !pc_HA_L_N_pd[scan[2:0]]; pre_b <= !pc_HB_L_N_pd[scan[2:0]];")
    w('            end')
    w('            if (took) begin')
    w('                want_m[tk] <= pre_m; want_b[tk] <= pre_b; seen[tk] <= 1\'b1;')
    w('                sure[tk] <= (pre_m == !pc_HA_L_N_pd[tk]) && (pre_b == !pc_HB_L_N_pd[tk]);')
    w('            end')
    w("            if (!in_turn && seen == 8'hFF) begin whole <= 1'b1; seen <= 8'd0; end")
    w('        end')
    w('    always @(posedge clk)')
    w('        if (rst_n && cap_stb && JUMPERED && whole && !in_turn) begin')
    w('            n_lchk = n_lchk + 1;')
    w('            if (((b_lamp_m ^ want_m) | (b_lamp_b ^ want_b)) & sure) begin')
    w('                n_lbad = n_lbad + 1;')
    w('                if (n_lbad <= 3)')
    w('                    $display("  BLOCK-STACK %m: lamps wrong at %0t: M %b want %b, BUSY %b want %b (sure %b)",')
    w('                             $time, b_lamp_m, want_m, b_lamp_b, want_b, sure);')
    w('            end')
    w('        end')
    w('    final if (n_lbad != 0)')
    w('        $display("  BLOCK-STACK %m: lamps wrong at %0d of %0d samples", n_lbad, n_lchk);')
    w('        else if (JUMPERED) $display("  block-stack %m: lamps right at %0d of %0d samples", n_lchk, n_lchk);')
    w('')
    w("    wire _unused = &{1'b0, frame_stb, fill, 1'b0};")
    w('    end endgenerate')
    w('endmodule')
    (GEN / 'block_stack.v').write_text('\n'.join(w.lines) + '\n')
    print(f"wrote {GEN / 'block_stack.v'}: {len(STACK)} stack nets, {len(LINK)} link nets, "
          f"{len(clash_terms)} with more than one strong driver")


if __name__ == '__main__':
    main()
