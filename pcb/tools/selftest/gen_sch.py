#!/usr/bin/env python3
"""The selftest toy, drawn with sch.py.  Writes OUT/selftest.kicad_sch (+ rc_det.kicad_sch).

    python3 gen_sch.py [OUT]          default pcb/out/selftest/toy

What it exercises (and ref.v restates by hand):
  U1 74HC151 (a 74LS151 symbol, Value 74HC151) picks D[S] -> MUX / MUX_N
  U2 74HC14, all seven units, every one used
  U3 74HC125: two tri-state drivers on one net OWN (a contention monitor), plus
     R5 4k7 from FILL -- a resistor from a SIGNAL net, a weak driver of OWN
  JP1 2x8 lane jumper, Sim.Jumper = one:LANE: OWN onto lane LANE of LANE0..7
  Q1 (a PROJECT symbol, drain typed open_collector) open drain onto HA_L,
     pulled up on the card by R1: a port bundle with _pd and _we/_wo
  Q2, Q3 stock 2N7002 wired-OR onto BUSY_N, pulled up by R4: resolved on card
  R6 33R series from a '14 output to the edge pin YB: a link, not a weak driver
  DETM, DETE: one rc_det.kicad_sch placed twice, each with its own Sim.Macro
     (rc_det, different T_ARM/T_REL); the R-D-R-C inside is replaced by the cell
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import kisexp  # noqa: E402
from kisexp import Q, dump  # noqa: E402
from sch import Project  # noqa: E402

OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parent.parent / 'out' / 'selftest' / 'toy'


def project_lib(path):
    """A one-symbol project library: the stock 2N7002 with its drain typed
    open_collector, so ERC and net2v both see an open drain."""
    s = kisexp.flat_symbol('Transistor_FET:2N7002')
    s = kisexp.parse(dump(s).replace('"Transistor_FET:2N7002"', '"Q_NMOS_OD"').replace('"2N7002_', '"Q_NMOS_OD_'))
    for sub in kisexp.kids(s, 'symbol'):
        for p in kisexp.kids(sub, 'pin'):
            if str(kisexp.kid(p, 'name')[1]) == 'D':
                p[1] = 'open_collector'
    for pr in kisexp.kids(s, 'property'):
        if pr[1] == 'Value':
            pr[2] = Q('Q_NMOS_OD')
    lib = ['kicad_symbol_lib', ['version', 20241209], ['generator', Q('kicad_symbol_editor')],
           ['generator_version', Q('10.0')], s]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(dump(lib) + '\n')


def build(out=OUT):
    out = Path(out)
    libp = out / 'lib' / 'selftest.kicad_sym'
    project_lib(libp)
    prj = Project('selftest', out, libs={'selftest': libp})
    top = prj.root
    top.title('pcb/tools selftest toy', rev='1', date='2026-09-25',
              comments=['Generated by pcb/tools/selftest/gen_sch.py -- do not edit by hand',
                        'Checked by ERC, then net2v.py against ref.v in lockstep, then placed, routed, DRC'])

    j1 = {'1': ['p:+5V', 'p:PWR_FLAG'], '2': ['p:GND', 'p:PWR_FLAG']}
    for i in range(8):
        j1[str(3 + i)] = f'D{i}'
        j1[str(21 + i)] = f'LANE{i}'
    j1.update({'11': 'S0', '12': 'S1', '13': 'S2', '14': 'E_N', '15': 'OE_N', '16': 'FILL', '17': 'HOOK',
               '18': 'FM', '19': 'BUSY', '20': 'HA_L', '29': 'OE2_N', '30': 'OWN_N', '31': 'YB'})
    for p in range(32, 41):
        j1[str(p)] = 'p:GND'
    top.text('Edge: every signal of the toy, GND on 32-40')
    top.part('Connector_Generic:Conn_02x20_Odd_Even', 'J1', 'EDGE', pins=j1)
    top.newcol()

    top.part('74xx:74LS151', 'U1', '74HC151', pins={
        '4': 'D0', '3': 'D1', '2': 'D2', '1': 'D3', '15': 'D4', '14': 'D5', '13': 'D6', '12': 'D7',
        '11': 'S0', '10': 'S1', '9': 'S2', '7': 'E_N', '5': 'MUX', '6': 'MUX_N', '16': 'p:+5V', '8': 'p:GND'})
    top.ic('74xx:74LS125', 'U3', '74HC125', units={
        1: {'1': 'OE_N', '2': 'MUX', '3': 'OWN'},
        2: {'4': 'OE2_N', '5': 'FM_N', '6': 'OWN'},
        3: {'10': 'p:+5V', '9': 'p:GND', '8': 'nc'},
        4: {'13': 'p:+5V', '12': 'p:GND', '11': 'nc'},
        5: {'14': 'p:+5V', '7': 'p:GND'}})
    top.newcol()
    top.ic('74xx:74HC14', 'U2', '74HC14', units={
        1: {'1': 'FM_RC', '2': 'FM_N'}, 2: {'3': 'FM_N', '4': 'FM'},
        3: {'5': 'FE_RC', '6': 'FE_N'}, 4: {'9': 'BUSY_N', '8': 'BUSY'},
        5: {'11': 'OWN', '10': 'OWN_N'}, 6: {'13': 'MUX', '12': 'MUXB_N'},
        7: {'14': 'p:+5V', '7': 'p:GND'}})
    top.newcol()
    top.part('Device:R', 'R5', '4k7', pins={'1': 'FILL', '2': 'OWN'})
    top.part('Device:R', 'R6', '33', pins={'1': 'MUXB_N', '2': 'YB'})
    top.text('JP1: ONE shunt, column k puts OWN on LANEk\nSim.Jumper = one:LANE')
    jp = {}
    for k in range(8):
        jp[str(2 * k + 1)] = 'OWN'
        jp[str(2 * k + 2)] = f'LANE{k}'
    top.part('Connector_Generic:Conn_02x08_Odd_Even', 'JP1', 'LANE', pins=jp, fields={'Sim.Jumper': 'one:LANE'})
    top.newcol()
    top.part('selftest:Q_NMOS_OD', 'Q1', '2N7002', pins={'G': 'MUX_N', 'S': 'p:GND', 'D': 'HA_L'},
             footprint='Package_TO_SOT_SMD:SOT-23')
    top.part('Device:R', 'R1', '10k', pins={'1': 'p:+5V', '2': 'HA_L'})
    top.part('Transistor_FET:2N7002', 'Q2', '2N7002', pins={'G': 'FM', 'S': 'p:GND', 'D': 'BUSY_N'})
    top.part('Transistor_FET:2N7002', 'Q3', '2N7002', pins={'G': 'FE_N', 'S': 'p:GND', 'D': 'BUSY_N'})
    top.part('Device:R', 'R4', '10k', pins={'1': 'p:+5V', '2': 'BUSY_N'})
    top.newcol()
    for i in (1, 2, 3):
        top.part('Device:C', f'C{i}', '100n', pins={'1': 'p:+5V', '2': 'p:GND'})

    det = prj.sheet('rc_det.kicad_sch')
    det.title('rc_det: diode + two R into an RC',
              comments=['Sim.Macro on each sheet symbol replaces everything here with pcb/models rc_det'])
    det.part('Device:R', 'R1', '1k', pins={'1': 'h:IN/input', '2': 'MID'})
    det.part('Device:D', 'D1', '1N4148', pins={'A': 'MID', 'K': 'h:OUT/output'})
    det.part('Device:R', 'R2', '220k', pins={'1': 'h:IN/input', '2': 'h:OUT/output'})
    det.part('Device:C', 'C1', '1u', pins={'1': 'h:OUT/output', '2': 'p:GND'})
    top.newcol()
    top.place_sheet(det, 'DETM', pins={'IN': 'HOOK', 'OUT': 'FM_RC'},
                    fields={'Sim.Macro': 'rc_det T_ARM=4 T_REL=12'})
    top.place_sheet(det, 'DETE', pins={'IN': 'MUX', 'OUT': 'FE_RC'},
                    fields={'Sim.Macro': 'rc_det T_ARM=2 T_REL=6'})
    return prj.write()


if __name__ == '__main__':
    print("wrote", build())
