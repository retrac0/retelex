#!/usr/bin/env python3
"""Write KiCad 10 schematics by script.  No wires: every connection is a label,
power symbol or no-connect flag placed exactly on a pin endpoint, so a sheet is
correct by construction and still legible when opened in KiCad.

    from sch import Project
    prj = Project('card', '/path/to/outdir')           # root sheet = card.kicad_sch
    top = prj.root
    top.title('Port card', rev='A', comments=['generated by gen.py'])
    top.part('74xx:74LS151', 'U1', value='74HC151', pins={'4': 'D0', ..., '8': 'p:GND'})
    det = prj.sheet('rc_det.kicad_sch')                # a sheet FILE
    det.part('Device:R', 'R1', '1k', pins={'1': 'h:IN', '2': 'MID'})
    top.place_sheet(det, 'DETM', pins={'IN': 'HOOK', 'OUT': 'FM_RC'},
                    fields={'Sim.Macro': 'rc_det T_ARM=16 T_REL=256 tick:@tick_1k'})
    top.place_sheet(det, 'DETE', pins={...})          # the same file, a second instance
    prj.write()
    sch.erc(prj.root_path)                             # -> (ok, [violations])

Connection specs (a pin's value in pins={...}; a list gives several):
    'NAME'        local label            'g:NAME'   global label
    'h:NAME'      hierarchical label (shape from the pin type; 'h:NAME/output' to force)
    'p:+5V'       power symbol (+5V GND VCC +12V -12V PWR_FLAG ...), unique #PWR refs
    'nc'          no-connect flag
Pins are keyed by number, or by name when the name is unique in the unit
(key FETs by name: 2N7000 and 2N7002 number G,S,D differently).  Every pin of
the unit must be given unless strict=False.

Placement: pass at=(x, y) (snapped to the 2.54 mm grid), or leave it out and
the part flows into columns (Sheet.newcol() breaks a column).  paper='auto'
picks the smallest of A4..A0 that holds the flow.

References on a sheet file placed more than once: a plain 'U1' becomes U101,
U201, ... (instance number x 100); a list gives one ref per instance; a
string with '{i}' (0-based) or '{n}' (1-based) is a template.

CLI:
    sch.py pins 74xx:74LS151          pin table of a symbol (units, numbers, names, types)
    sch.py erc top.kicad_sch          ERC, all severities, JSON parsed; exit 1 on violations
"""
