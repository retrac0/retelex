def kuid(key):
    """A UUID that is a function of a name.  Symbols and sheets are keyed by
    what they are (sheet file, reference, unit; parent and sheet name), so a
    schematic regenerated from the same description keeps every UUID -- which
    is what ties a footprint on the board to its symbol."""
    return str(_uuid_mod.uuid5(_NS, key))


def snap(v, g=GRID):
    return round(round(v / g) * g, 4)


def snap_up(v, g=GRID):
    import math
    return round(math.ceil(v / g - 1e-9) * g, 4)


def _prop(name, value, x, y, hide=False, ang=0, justify=None):
    p = ['property', Q(name), Q(value), ['at', round(x, 4), round(y, 4), ang]]
    if hide:
        p.append(['hide', 'yes'])
    eff = ['effects', FONT]
    if justify:
        eff.append(['justify'] + justify)
    p.append(eff)
    return p


def default_footprint(lib_id):
    if lib_id in FOOTPRINTS:
        return FOOTPRINTS[lib_id]
    fp = kisexp.props(flat_symbol(lib_id)).get('Footprint', '')
    if fp:
        return fp
    if lib_id.startswith(('74xx:', '4xxx:')):
        n = len({p['num'] for p in sym_pins(lib_id)})
        return DIP_BY_PINS.get(n, '')
    m = re.match(r'Connector_Generic:Conn_02x(\d\d)_', lib_id)
    if m:
        return f"Connector_PinHeader_2.54mm:PinHeader_2x{m.group(1)}_P2.54mm_Vertical"
    m = re.match(r'Connector_Generic:Conn_01x(\d\d)', lib_id)
    if m:
        return f"Connector_PinHeader_2.54mm:PinHeader_1x{m.group(1)}_P2.54mm_Vertical"
    return ''


def _specs(spec):
    if spec is None or spec == '':
        return []
    return list(spec) if isinstance(spec, (list, tuple)) else [spec]


def _text_len(s):
    return CHAR_W * len(s)


def _spec_len(spec):
    """How far a connection spec reaches out from the pin (layout estimate)."""
    if spec == 'nc':
        return 1.0
    if spec.startswith('p:'):
        return 5.1
    if spec.startswith('g:'):
        return _text_len(spec[2:]) + 4.0
    if spec.startswith('h:'):
        return _text_len(spec[2:].partition('/')[0]) + 3.0
    return _text_len(spec) + 1.0


HIER_SHAPE = {'input': 'input', 'output': 'output', 'tri_state': 'tri_state',
              'bidirectional': 'bidirectional', 'passive': 'passive', 'open_collector': 'output',
              'open_emitter': 'output', 'power_out': 'output', 'power_in': 'input'}


# --------------------------------------------------------------- requests
class Part:
    def __init__(self, sheet, lib_id, ref, value, at, rot, mirror, unit, footprint, fields, pins,
                 strict, dnp, exclude_from_sim, in_bom, on_board):
        self.sheet, self.lib_id, self.ref, self.value = sheet, lib_id, ref, value
        self.at, self.rot, self.mirror, self.unit = at, rot, mirror, unit
        self.footprint, self.fields = footprint, dict(fields or {})
        self.strict, self.dnp, self.xsim, self.in_bom, self.on_board = strict, dnp, exclude_from_sim, in_bom, on_board
        self.uuid = kuid(f"sym:{sheet.project.name}:{sheet.file}:{ref}:{unit}")
        self.node = flat_symbol(lib_id)
        allp = [p for p in sym_pins(self.node) if p['unit'] in (0, unit)]
        if unit not in sym_units(self.node):
            raise ValueError(f"{ref}: {lib_id} has no unit {unit} (units {sym_units(self.node)})")
        self.pins = allp
        self.conns = {}                      # pin number -> [spec]
        for key, spec in (pins or {}).items():
            key = str(key)
            hits = [p for p in allp if p['num'] == key] or [p for p in allp if p['name'] == key]
            if len(hits) != 1:
                raise ValueError(f"{ref} unit {unit} ({lib_id}): pin '{key}' "
                                 f"{'not found' if not hits else 'is ambiguous'}")
            self.conns.setdefault(hits[0]['num'], []).extend(_specs(spec))
        if strict:
            miss = [f"{p['num']}({p['name']})" for p in allp if p['num'] not in self.conns]
            if miss:
                raise ValueError(f"{ref} unit {unit} ({lib_id}): pins not connected: {' '.join(miss)} "
                                 f"(give 'nc', or strict=False)")

    def extent(self):
        """Extent around the symbol origin, pins' labels included."""
        x0, y0, x1, y1 = sym_bbox(self.node, self.unit, self.rot, self.mirror)
        bx = [x0, x1]
        by = [y0, y1]
        for p in self.pins:
            specs = self.conns.get(p['num'], [])
            if not specs:
                continue
            px, py = pin_xy(0, 0, self.rot, self.mirror, p['x'], p['y'])
            ox, oy = pin_outward(self.rot, self.mirror, p['rot'])
            reach = max(_spec_len(s) for s in specs)
            if ox:
                bx.append(px + ox * reach)
            else:
                by.append(py + oy * reach)
            bx.append(px), by.append(py)
        return min(bx), min(by) - 5.2, max(bx), max(by) + 5.2


class SheetRef:
    def __init__(self, parent, child, name, at, pins, fields, width):
        self.parent, self.child, self.name, self.at = parent, child, name, at
        self.pins = {k: _specs(v) for k, v in (pins or {}).items()}
        self.fields = dict(fields or {})
        self.uuid = kuid(f"sheet:{parent.project.name}:{parent.file}:{name}")
        self.width = width

    def layout_pins(self):
        """[(name, shape, side)]: inputs/bidirectional/passive left, outputs/tri right."""
        shapes = self.child.hier_labels()
        extra = set(self.pins) - set(shapes)
        if extra:
            raise ValueError(f"sheet {self.name}: no hierarchical label for pins {sorted(extra)} "
                             f"in {self.child.file}")
        missing = set(shapes) - set(self.pins)
        if missing:
            raise ValueError(f"sheet {self.name}: pins {sorted(missing)} not connected (give 'nc'?)")
        left = [(n, s) for n, s in shapes.items() if s not in ('output', 'tri_state')]
        right = [(n, s) for n, s in shapes.items() if s in ('output', 'tri_state')]
        return left, right

    def size(self):
        left, right = self.layout_pins()
        n = max(len(left), len(right), 1)
        wl = max([_text_len(x) for x, _ in left] + [0])
        wr = max([_text_len(x) for x, _ in right] + [0])
        w = self.width or snap_up(max(wl + wr + 5.08, _text_len(self.name) + 2.54, 20.32))
        return w, GRID * (n + 1)

    def extent(self):
        w, h = self.size()
        left, right = self.layout_pins()
        el = max([max(_spec_len(s) for s in self.pins[n]) if self.pins[n] else 0 for n, _ in left] + [0])
        er = max([max(_spec_len(s) for s in self.pins[n]) if self.pins[n] else 0 for n, _ in right] + [0])
        nf = sum(1 for k in self.fields if not k.startswith('_'))
        return -el, -2.6, w + er, h + 2.6 + 2.54 * (1 + nf)


class Text:
    def __init__(self, text, at, size):
        self.text, self.at, self.size = text, at, size
        self.uuid = None                 # given in Sheet._build, by position in the sheet

    def extent(self):
        lines = self.text.split('\n')
        w = max(len(s) for s in lines) * self.size * 0.87
        return 0, -self.size, w, self.size * 1.7 * len(lines)


class _ColBreak:
    at = None


# ------------------------------------------------------------------ sheets
class Sheet:
    """One .kicad_sch file.  Build it with part(), label(), text() and
    place_sheet(); Project.write() lays out and writes every file."""

    def __init__(self, project, file, paper='auto'):
        self.project, self.file, self.paper = project, file, paper
        self.uuid = kuid(f"file:{project.name}:{file}")
        self.items = []
        self.loose = []              # explicit labels / power / nc: (spec, x, y, outward)
        self.tb = None
        self.paths = []              # instance paths, filled by Project.write
        self.margin = 25.4

    # ---- content
    def part(self, lib_id, ref, value=None, pins=None, at=None, rot=0, mirror=None, unit=1,
             footprint=None, fields=None, strict=True, dnp=False, exclude_from_sim=False,
             in_bom=True, on_board=True):
        """Place one unit of a symbol.  value defaults to the symbol name;
        footprint=None picks a stock THT default, '' leaves it empty."""
        if value is None:
            value = lib_id.split(':', 1)[1]
        if footprint is None:
            footprint = default_footprint(lib_id)
        p = Part(self, lib_id, ref, value, at, rot, mirror, unit, footprint, fields, pins,
                 strict, dnp, exclude_from_sim, in_bom, on_board)
        self.items.append(p)
        return p

    def ic(self, lib_id, ref, value=None, units=None, **kw):
        """Every unit of a multi-unit part in one call: units = {unit: pins}."""
        return [self.part(lib_id, ref, value, pins=pins, unit=u, **kw) for u, pins in units.items()]

    def place_sheet(self, child, name, pins=None, at=None, fields=None, width=None):
        """A sheet symbol for the Sheet `child` (a sheet file; place it as often
        as you like).  pins = {hierarchical label: connection spec}."""
        if any(isinstance(i, SheetRef) and i.name == name for i in self.items):
            raise ValueError(f"sheet name {name} used twice on {self.file}")
        r = SheetRef(self, child, name, at, pins, fields, width)
        self.items.append(r)
        return r

    def text(self, text, at=None, size=1.27):
        t = Text(text, at, size)
        self.items.append(t)
        return t

    def label(self, spec, at, outward=(1, 0)):
        """A loose label / power symbol / nc at an explicit point."""
        self.loose.append((spec, float(at[0]), float(at[1]), tuple(outward)))

    def newcol(self):
        self.items.append(_ColBreak())

    def title(self, title, rev='', date='', company='', comments=()):
        self.tb = dict(title=title, rev=rev, date=date, company=company, comments=list(comments))

    def hier_labels(self):
        """{name: shape} of the hierarchical labels this sheet file carries."""
        out = {}
        for it in self.items:
            if isinstance(it, Part):
                for p in it.pins:
                    for s in it.conns.get(p['num'], []):
                        if s.startswith('h:'):
                            n, _, shape = s[2:].partition('/')
                            out.setdefault(n, shape or HIER_SHAPE.get(p['type'], 'bidirectional'))
            elif isinstance(it, SheetRef):
                for n, specs in it.pins.items():
                    for s in specs:
                        if s.startswith('h:'):
                            nm, _, shape = s[2:].partition('/')
                            out.setdefault(nm, shape or 'bidirectional')
        for s, _, _, _ in self.loose:
            if s.startswith('h:'):
                n, _, shape = s[2:].partition('/')
                out.setdefault(n, shape or 'bidirectional')
        return out

    # ---- layout
    def _flow(self, pw, ph):
        """Place every item without at= into columns.  Returns True if it fits."""
        m = self.margin
        x, y, colw = m, m, 0.0
        ymax = ph - m - 36          # the title block sits in the bottom right corner
        xmax = pw - m
        fits = True
        for it in self.items:
            if isinstance(it, _ColBreak):
                if colw:
                    x, y, colw = x + colw + 10.16, m, 0.0
                continue
            if it.at is not None and not getattr(it, '_flowed', False):
                continue
            x0, y0, x1, y1 = it.extent()
            w, h = x1 - x0, y1 - y0
            if y > m and y + h > ymax:
                x, y, colw = x + colw + 10.16, m, 0.0
            ax, ay = snap_up(x - x0), snap_up(y - y0)
            it.at, it._flowed = (ax, ay), True
            y = ay + y1 + 5.08
            colw = max(colw, w)
            if x + w > xmax or ay + y1 > ph - m:
                fits = False
        return fits

    def layout(self):
        sizes = [p for p in PAPERS if p[0] == self.paper] if self.paper != 'auto' else PAPERS
        if not sizes:
            raise ValueError(f"paper {self.paper}")
        for name, w, h in sizes:
            for it in self.items:
                if getattr(it, '_flowed', False):
                    it.at, it._flowed = None, False
            if self._flow(w, h):
                self._paper = name
                return
        self._paper = sizes[-1][0]
        print(f"warning: {self.file}: content overflows {self._paper}", file=sys.stderr)

    # ---- output
    def _sym_node(self, lib_id, x, y, rot, mirror, unit, refs, value, footprint, fields, power,
                  dnp=False, xsim=False, in_bom=True, on_board=True, uuid=None, fieldpos=None):
        prj = self.project
        s = ['symbol', ['lib_id', Q(lib_id)], ['at', x, y, rot]]
        if mirror:
            s.append(['mirror', mirror])
        yn = lambda b: 'yes' if b else 'no'  # noqa: E731
        s += [['unit', unit], ['body_style', 1], ['exclude_from_sim', yn(xsim)],
              ['in_bom', yn(in_bom and not power)], ['on_board', yn(on_board and not power)],
              ['in_pos_files', yn(not power)], ['dnp', yn(dnp)], ["uuid", Q(uuid or self._uid())]]
        (rx, ry, rj), (vx, vy, vj) = fieldpos or ((x, y - 5.08, None), (x, y + 5.08, None))
        s.append(_prop('Reference', refs[0], rx, ry, hide=power, justify=rj))
        s.append(_prop('Value', value, vx, vy, hide=False, justify=vj))
        s.append(_prop('Footprint', footprint or '', x, y, hide=True))
        s.append(_prop('Datasheet', '', x, y, hide=True))
        fy = vy + 2.54
        for k, v in (fields or {}).items():
            # notes (RTL, Function) ride along hidden -- the Properties dialog
            # and the netlist have them; a Sim.* setting is shown, it changes
            # what the netlist check simulates
            shown = k.startswith('Sim.')
            s.append(_prop(k, str(v), vx, fy, hide=not shown, justify=vj))
            if shown:
                fy += 2.54
        for p in sym_pins(lib_id):
            if p['unit'] in (0, unit):
                s.append(['pin', Q(p['num']), ['uuid', Q(self._uid())]])
        s.append(['instances', ['project', Q(prj.name)] +
                  [['path', Q(pa), ['reference', Q(r)], ['unit', unit]] for pa, r in zip(self.paths, refs)]])
        prj._libs[lib_id] = flat_symbol(lib_id)
        return s

    def _refs(self, spec):
        n = len(self.paths)
        if isinstance(spec, (list, tuple)):
            if len(spec) != n:
                raise ValueError(f"{self.file}: {len(spec)} refs for {n} instances")
            return list(spec)
        if '{' in spec:
            return [spec.format(i=i, n=i + 1) for i in range(n)]
        if n == 1:
            return [spec]
        m = re.fullmatch(r'([A-Za-z#_]+)(\d+)', spec)
        if not m:
            raise ValueError(f"{self.file} is placed {n} times: give ref '{spec}' as a list or template")
        return [f"{m.group(1)}{(i + 1) * 100 + int(m.group(2))}" for i in range(n)]

    def _attach(self, out, spec, px, py, outward, pintype='passive'):
        prj = self.project
        key = (round(px, 3), round(py, 3))
        if spec != 'nc' and not spec.startswith('p:PWR_FLAG'):
            old = self._points.get(key)
            if old and old != spec:
                raise ValueError(f"{self.file}: two nets on one point {key}: {old} and {spec}")
            self._points[key] = spec
        ang = {(1, 0): 0, (0, -1): 90, (-1, 0): 180, (0, 1): 270}[outward]
        just = 'left' if ang in (0, 90) else 'right'
        if spec == 'nc':
            out.append(['no_connect', ['at', px, py], ['uuid', Q(self._uid())]])
        elif spec.startswith('p:'):
            name = spec[2:]
            down = name in ('GND', 'GNDD', 'GNDA', '-12V', '-48V', '-5V', 'VEE')
            if name == 'PWR_FLAG':      # across the pin, so it does not sit on the rail symbol
                outward = (0, -1) if outward[1] == 0 else (1, 0)
            rot = ({(0, 1): 0, (1, 0): 90, (0, -1): 180, (-1, 0): 270} if down else
                   {(0, -1): 0, (-1, 0): 90, (0, 1): 180, (1, 0): 270})[outward]
            tag = 'FLG' if name == 'PWR_FLAG' else 'PWR'
            refs = [f"#{tag}{next(prj._pwrseq):04d}" for _ in self.paths]
            vx, vy = px + outward[0] * 3.81, py + outward[1] * 3.81
            if outward[1] == 0:
                vy -= 1.27
            out.append(self._sym_node(f"power:{name}", px, py, rot, None, 1, refs, name, '', None,
                                      power=True, fieldpos=((px, py, None), (vx, vy, None))))
        elif spec.startswith('g:'):
            out.append(['global_label', Q(spec[2:]), ['shape', 'bidirectional'], ['at', px, py, ang],
                        ['fields_autoplaced', 'yes'], ['effects', FONT, ['justify', just]],
                        ['uuid', Q(self._uid())],
                        ['property', Q('Intersheetrefs'), Q('${INTERSHEET_REFS}'), ['at', px, py, 0],
                         ['hide', 'yes'], ['effects', FONT]]])
        elif spec.startswith('h:'):
            name, _, shape = spec[2:].partition('/')
            shape = shape or HIER_SHAPE.get(pintype, 'bidirectional')
            out.append(['hierarchical_label', Q(name), ['shape', shape], ['at', px, py, ang],
                        ['effects', FONT, ['justify', just]], ['uuid', Q(self._uid())]])
        else:
            out.append(['label', Q(spec), ['at', px, py, ang], ['effects', FONT, ['justify', just, 'bottom']],
                        ['uuid', Q(self._uid())]])

    def _fieldpos(self, it, x, y):
        """Reference and Value on a side of the body that has no pins."""
        x0, y0, x1, y1 = sym_bbox(it.node, it.unit, it.rot, it.mirror)
        sides = {pin_outward(it.rot, it.mirror, p['rot']) for p in it.pins}
        top, bottom = (0, -1) not in sides, (0, 1) not in sides
        if top and bottom:
            return (x, y + y0 - 1.27, None), (x, y + y1 + 1.905, None)
        if (1, 0) not in sides:
            return (x + x1 + 1.27, y - 1.27, ['left']), (x + x1 + 1.27, y + 1.27, ['left'])
        if (-1, 0) not in sides:
            return (x + x0 - 1.27, y - 1.27, ['right']), (x + x0 - 1.27, y + 1.27, ['right'])
        if top:
            return (x, y + y0 - 3.81, None), (x, y + y0 - 1.27, None)
        if bottom:
            return (x, y + y1 + 1.905, None), (x, y + y1 + 4.445, None)
        return (x + x0, y + y0 - 1.27, ['left']), (x + x0, y + y1 + 1.905, ['left'])

    def _uid(self):
        self._n = getattr(self, '_n', 0) + 1
        return kuid(f"item:{self.project.name}:{self.file}:{self._n}")

    def _build(self):
        prj = self.project
        self._n = 0
        self._points = {}
        out = []
        for it in self.items:
            if isinstance(it, Part):
                x, y = snap(it.at[0]), snap(it.at[1])
                refs = self._refs(it.ref)
                out.append(self._sym_node(it.lib_id, x, y, it.rot, it.mirror, it.unit, refs, it.value,
                                          it.footprint, it.fields, False, it.dnp, it.xsim, it.in_bom,
                                          it.on_board, uuid=it.uuid, fieldpos=self._fieldpos(it, x, y)))
                for p in it.pins:
                    px, py = pin_xy(x, y, it.rot, it.mirror, p['x'], p['y'])
                    ow = pin_outward(it.rot, it.mirror, p['rot'])
                    for spec in it.conns.get(p['num'], []):
                        self._attach(out, spec, px, py, ow, p['type'])
            elif isinstance(it, SheetRef):
                x, y = snap(it.at[0]), snap(it.at[1])
                w, h = it.size()
                left, right = it.layout_pins()
                s = ['sheet', ['at', x, y], ['size', w, h], ['exclude_from_sim', 'no'],
                     ['in_bom', 'yes'], ['on_board', 'yes'], ['dnp', 'no'],
                     ['stroke', ['width', 0.1524], ['type', 'solid']], ['fill', ['color', 0, 0, 0, 0.0]],
                     ['uuid', Q(it.uuid)],
                     _prop('Sheetname', it.name, x, y - 0.7, justify=['left', 'bottom']),
                     _prop('Sheetfile', it.child.file, x, y + h + 0.6, justify=['left', 'top'])]
                fy = y + h + 3.2
                for k, v in it.fields.items():
                    s.append(_prop(k, str(v), x, fy, justify=['left', 'top']))
                    fy += 2.54
                for side, lst in (('L', left), ('R', right)):
                    for i, (pn, shape) in enumerate(lst):
                        py = round(y + GRID * (i + 1), 4)
                        px = x if side == 'L' else round(x + w, 4)
                        s.append(['pin', Q(pn), shape, ['at', px, py, 180 if side == 'L' else 0],
                                  ['uuid', Q(self._uid())],
                                  ['effects', FONT, ['justify', 'left' if side == 'L' else 'right']]])
                        for spec in it.pins[pn]:
                            self._attach(out, spec, px, py, (-1, 0) if side == 'L' else (1, 0))
                s.append(['instances', ['project', Q(prj.name)] +
                          [['path', Q(pa), ['page', Q(str(prj._page[pa + '/' + it.uuid]))]] for pa in self.paths]])
                out.append(s)
            elif isinstance(it, Text):
                x, y = it.at
                out.append(['text', Q(it.text), ['exclude_from_sim', 'no'], ['at', x, y, 0],
                            ['effects', ['font', ['size', it.size, it.size]], ['justify', 'left', 'top']],
                            ['uuid', Q(self._uid())]])
        for spec, x, y, ow in self.loose:
            self._attach(out, spec, x, y, ow)
        return out

    def _tree(self, items, root):
        tree = ['kicad_sch', ['version', SCH_VERSION], ['generator', Q('eeschema')],
                ['generator_version', Q('10.0')], ['uuid', Q(self.uuid)], ['paper', Q(self._paper)]]
        if self.tb:
            tb = ['title_block', ['title', Q(self.tb['title'])]]
            if self.tb['date']:
                tb.append(['date', Q(self.tb['date'])])
            if self.tb['rev']:
                tb.append(['rev', Q(self.tb['rev'])])
            if self.tb['company']:
                tb.append(['company', Q(self.tb['company'])])
            for i, c in enumerate(self.tb['comments'][:9], 1):
                tb.append(['comment', i, Q(c)])
            tree.append(tb)
        tree.append(['lib_symbols'] + [self.project._libs[k] for k in sorted(self._used)])
        tree += items
        if root:
            tree.append(['sheet_instances', ['path', Q('/'), ['page', Q('1')]]])
        tree.append(['embedded_fonts', 'no'])
        return tree


class Project:
    """A schematic hierarchy.  The root sheet file is <name>.kicad_sch in outdir."""

    def __init__(self, name, outdir, libs=None, fp_libs=None, erc_ignore=()):
        self.name, self.outdir = name, Path(outdir)
        self.erc_ignore = tuple(erc_ignore)     # ERC rule names set to 'ignore' in the .kicad_pro
        self.libs = dict(libs or {})           # project symbol libraries: nick -> .kicad_sym
        self.fp_libs = dict(fp_libs or {})     # project footprint libraries: nick -> .pretty
        for nick, path in self.libs.items():
            kisexp.register_lib(nick, path)
        self.sheets = {}
        self.root = self.sheet(f"{name}.kicad_sch")
        self._libs = {}

    def sheet(self, file, paper='auto'):
        if file in self.sheets:
            raise ValueError(f"sheet file {file} exists")
        s = Sheet(self, file, paper)
        self.sheets[file] = s
        return s

    @property
    def root_path(self):
        return self.outdir / self.root.file

    def _walk(self, sheet, paths):
        sheet.paths += paths
        for it in sheet.items:
            if isinstance(it, SheetRef):
                cp = []
                for p in paths:
                    q = p + '/' + it.uuid
                    self._page[q] = next(self._pageseq)
                    cp.append(q)
                self._walk(it.child, cp)

    def write(self):
        self.outdir.mkdir(parents=True, exist_ok=True)
        self._pwrseq = itertools.count(1)
        self._pageseq = itertools.count(2)
        self._page = {}
        for s in self.sheets.values():
            s.paths = []
        root_path = '/' + self.root.uuid
        self._walk(self.root, [root_path])
        unused = [f for f, s in self.sheets.items() if not s.paths]
        if unused:
            raise ValueError(f"sheet files never placed: {unused}")
        for s in self.sheets.values():
            s.layout()
        files = []
        for s in self.sheets.values():
            items = s._build()
            s._used = set(_walk_syms(items))
            tree = s._tree(items, s is self.root)
            p = self.outdir / s.file
            p.write_text(dump(tree) + '\n')
            files.append(p)
        pro = {"meta": {"filename": f"{self.name}.kicad_pro", "version": 3},
               "sheets": [[self.root.uuid, "Root"]] +
                         [[it.uuid, it.name] for s in self.sheets.values() for it in s.items
                          if isinstance(it, SheetRef)],
               "text_variables": {}}
        if self.erc_ignore:
            pro["erc"] = {"rule_severities": {r: "ignore" for r in self.erc_ignore}}
        (self.outdir / f"{self.name}.kicad_pro").write_text(json.dumps(pro, indent=2) + '\n')
        if self.libs:
            rows = ''.join(f'\t(lib (name "{n}") (type "KiCad") (uri "${{KIPRJMOD}}/{os.path.relpath(p, self.outdir)}") '
                           f'(options "") (descr ""))\n' for n, p in self.libs.items())
            (self.outdir / 'sym-lib-table').write_text(f"(sym_lib_table\n\t(version 7)\n{rows})\n")
        if self.fp_libs:
            rows = ''.join(f'\t(lib (name "{n}") (type "KiCad") (uri "${{KIPRJMOD}}/{os.path.relpath(p, self.outdir)}") '
                           f'(options "") (descr ""))\n' for n, p in self.fp_libs.items())
            (self.outdir / 'fp-lib-table').write_text(f"(fp_lib_table\n\t(version 7)\n{rows})\n")
        return self.root_path


def _walk_syms(items):
    for i in items:
        if isinstance(i, list) and i and i[0] == 'symbol':
            yield str(kisexp.kid(i, 'lib_id')[1])


# --------------------------------------------------------------------- ERC
def erc(sch_path, severity='--severity-all', out=None):
    """Run kicad-cli ERC.  Returns (ok, [(severity, type, description, items)])."""
    sch_path = Path(sch_path)
    out = Path(out) if out else sch_path.with_suffix('.erc.json')
    r = subprocess.run(['kicad-cli', 'sch', 'erc', severity, '--format', 'json', '-o', str(out), str(sch_path)],
                       capture_output=True, text=True)
    if not out.exists():
        raise RuntimeError(f"ERC did not run: {r.stdout}{r.stderr}")
    data = json.loads(out.read_text())
    vio = []
    for sh in data.get('sheets', []):
        for v in sh.get('violations', []):
            vio.append((v.get('severity'), v.get('type'), v.get('description'),
                        [f"{sh.get('path')}:{i.get('description')}" for i in v.get('items', [])]))
    return not vio, vio


def main(argv=None):
    import argparse
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    sub = ap.add_subparsers(dest='cmd', required=True)
    a = sub.add_parser('pins', help='pin table of a symbol')
    a.add_argument('lib_id')
    a.add_argument('--lib', action='append', default=[], help='nick=path.kicad_sym (project library)')
    b = sub.add_parser('erc', help='ERC with all severities; exit 1 on any violation')
    b.add_argument('sch')
    a2 = ap.parse_args(argv)
    if a2.cmd == 'pins':
        for spec in a2.lib:
            n, _, p = spec.partition('=')
            kisexp.register_lib(n, p)
        for p in sorted(sym_pins(a2.lib_id), key=lambda p: (p['unit'], int(p['num']) if p['num'].isdigit() else 999, p['num'])):
            print(f"unit {p['unit']:2}  pin {p['num']:>4}  {p['name']:<12} {p['type']:<15}"
                  f"{' hidden' if p['hidden'] else ''}")
        print(f"units {sym_units(a2.lib_id)}  default footprint '{default_footprint(a2.lib_id)}'")
        return 0
    ok, vio = erc(a2.sch)
    for sev, typ, desc, items in vio:
        print(f"{sev:8} {typ:28} {desc}  {'; '.join(items)}")
    print(f"ERC {'clean' if ok else f'{len(vio)} violation(s)'}: {a2.sch}")
    return 0 if ok else 1


if __name__ == '__main__':
    sys.exit(main())
