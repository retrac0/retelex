// tone_card -- every call-progress tone in the exchange, from one ROM and one
// counter.  common/tone-plan.md 4.
//
// A channel card like any other: it drives C_TX with dial tone and ties /ANS
// low, so its port answers at once and is never rung.  What is unusual is that
// it drives four more conductors off its rear connector -- two punched onto the
// C_TX nets of vacant slots, and the exchange's RBT and /RING_CAD buses.
//
//   plane A  425~25, the Australian warble   -> dial tone and ringback
//   plane B  600~120, the old Bell buzz      -> busy and cannot-complete
//
// Two images, four tones.  What separates dial from ringback, or busy from
// cannot-complete, is not the ROM: it is a cadence gate, and every gate is a
// tap off the same counter that addresses the ROM (tone-plan.md 4.2):
//
//   dial             plane A, ungated
//   ringback         plane A, gated by NOR(Q17, Q15)   -- the double pulse, 4.3
//   busy             plane B, gated by Q15             -- 0.512 / 0.512 s
//   cannot-complete  plane B, gated by Q14             -- 0.256 / 0.256 s, busy one stage faster
//   /RING_CAD        the ring gate, complemented
//
// A gated-off output sends FILL, which is what an idle port already carries, so
// the seam needs no synchronisation (tones.log, cadence: -44.7 dB worst).
//
// tone_rom.hex is generated by `python3 sim/tones.py image` and is the same
// image sim/out/tone_*.wav is rendered from.
`timescale 1ns/1ps

module tone_card #(
    parameter ROM_FILE = "rtl/tone_rom.hex",
    // The address is 13 bits: 8192 frames is 128 ms, and every burned frequency
    // is a multiple of 64000/8192 = 7.8125 Hz so the loop is seamless.
    parameter integer ABITS = 13,
    // The cadence taps.  A counter bit's period is 2^(n+1) frames; at 64 kHz
    // that is Q14 = 0.512 s, Q15 = 1.024 s, Q17 = 4.096 s.
    parameter integer TAP_CC   = 14,
    parameter integer TAP_BUSY = 15,
    parameter integer TAP_RING = 17
)(
    input      clk,
    input      frame_stb,        // one frame, 64 kHz
    input      fill,             // the bus's 1010: what a gated-off output sends

    output     c_tx,             // dial tone -- this card's own port
    output     a_tx,             // a source never answers
    output     ans_n,            // and is never rung

    output     ringback,         // -> the RBT conductor
    output     busy,             // -> punched onto a vacant slot's C_TX
    output     cannot,           // -> punched onto a vacant slot's C_TX
    output     ring_cad_n        // -> the /RING_CAD conductor, LOW while ringing
);
    // ---- one counter: the ROM address below, the cadence above -------------
    reg [TAP_RING:0] cnt /* verilator public */ = 0;
    always @(posedge clk) if (frame_stb) cnt <= cnt + 1'b1;

    // ---- the ROM, and the '74 that retimes it against the access glitch ----
    reg [7:0] rom [0:(1 << ABITS) - 1];
    initial $readmemh(ROM_FILE, rom);

    reg plane_a /* verilator public */ = 0;
    reg plane_b /* verilator public */ = 0;
    always @(posedge clk) if (frame_stb) begin
        plane_a <= rom[cnt[ABITS-1:0]][0];
        plane_b <= rom[cnt[ABITS-1:0]][1];
    end

    // ---- the cadence gates: taps and one NOR -------------------------------
    // /Q17 is a 2.048 s window; inside it Q15 completes exactly two cycles, so
    // the NOR is on, off, on, then silent for the rest of Q17 (tone-plan.md 4.3).
    wire ring_gate /* verilator public */ = ~(cnt[TAP_RING] | cnt[TAP_BUSY]);

    assign c_tx       = plane_a;
    assign ringback   = ring_gate      ? plane_a : fill;
    assign busy       = cnt[TAP_BUSY]  ? plane_b : fill;
    assign cannot     = cnt[TAP_CC]    ? plane_b : fill;
    assign ring_cad_n = ~ring_gate;              // the same gate, complemented

    assign a_tx  = 1'b0;
    assign ans_n = 1'b0;
endmodule
